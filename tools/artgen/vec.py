"""グラデーションつきのベクター画像を組み立てて、VectorDrawable の XML（と確認用の SVG）にする小さなライブラリ。

標準ライブラリのみ。アイコン（gen_icons.py）と UI の飾り用。座標は viewport の単位（左上が原点）。
出力は決定論的（同じ入力から同じ XML）。
"""

import math


def _f(v):
    s = "%.2f" % v
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _argb(color, alpha=1.0):
    """'#RRGGBB' と不透明度から '#AARRGGBB'。"""
    c = color.lstrip("#")
    if len(c) == 8:
        return "#" + c.upper()
    return "#%02X%s" % (max(0, min(255, round(alpha * 255))), c.upper())


class Linear:
    """線形グラデーション。stops は [(offset, '#RRGGBB' または '#AARRGGBB'), ...]。"""

    def __init__(self, x0, y0, x1, y1, stops):
        self.x0, self.y0, self.x1, self.y1, self.stops = x0, y0, x1, y1, _norm(stops)


class Radial:
    def __init__(self, cx, cy, r, stops):
        self.cx, self.cy, self.r, self.stops = cx, cy, r, _norm(stops)


def _norm(stops):
    if stops and not isinstance(stops[0], (tuple, list)):
        n = len(stops)
        return [(i / (n - 1), c) for i, c in enumerate(stops)]
    return list(stops)


def vgrad(y0, y1, *colors):
    """上から下への線形グラデーション（色を等間隔に並べる）。"""
    return Linear(0, y0, 0, y1, list(colors))


def hgrad(x0, x1, *colors):
    return Linear(x0, 0, x1, 0, list(colors))


# ---- パス文字列の部品 -------------------------------------------------------------
def circle(cx, cy, r):
    return ellipse(cx, cy, r, r)


def ellipse(cx, cy, rx, ry):
    return "M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z" % (
        _f(cx - rx), _f(cy), _f(rx), _f(ry), _f(2 * rx), _f(rx), _f(ry), _f(-2 * rx),
    )


def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    return (
        "M%s,%s h%s a%s,%s 0 0,1 %s,%s v%s a%s,%s 0 0,1 %s,%s h%s a%s,%s 0 0,1 %s,%s v%s a%s,%s 0 0,1 %s,%s Z"
        % (
            _f(x + r), _f(y), _f(w - 2 * r), _f(r), _f(r), _f(r), _f(r), _f(h - 2 * r),
            _f(r), _f(r), _f(-r), _f(r), _f(-(w - 2 * r)), _f(r), _f(r), _f(-r), _f(-r),
            _f(-(h - 2 * r)), _f(r), _f(r), _f(r), _f(-r),
        )
    )


def poly(pts, closed=True):
    d = "M" + " L".join("%s,%s" % (_f(x), _f(y)) for x, y in pts)
    return d + (" Z" if closed else "")


def star(cx, cy, ro, ri, n=5, rot=-90.0):
    pts = []
    for i in range(n * 2):
        r = ro if i % 2 == 0 else ri
        a = math.radians(rot + 180.0 * i / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return poly(pts)


def rot(pts, deg, cx, cy):
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * ca - (y - cy) * sa, cy + (x - cx) * sa + (y - cy) * ca) for x, y in pts]


class Vec:
    """1 枚のベクター画像。path / group を描画順に積む。"""

    def __init__(self, w=48, h=48, dp_w=None, dp_h=None):
        self.w, self.h = w, h
        self.dp_w, self.dp_h = dp_w or w, dp_h or h
        self.items = []
        self._stack = [self.items]

    # 図形 ---------------------------------------------------------------------
    def path(self, d, fill=None, stroke=None, sw=0.0, alpha=1.0, salpha=1.0, cap="round", join="round", evenodd=False):
        self._stack[-1].append(("path", d, fill, stroke, sw, alpha, salpha, cap, join, evenodd))
        return self

    def line(self, pts, stroke, sw, salpha=1.0, cap="round"):
        return self.path(poly(pts, closed=False), None, stroke, sw, salpha=salpha, cap=cap)

    def begin(self, rotate=0.0, px=0.0, py=0.0, tx=0.0, ty=0.0, sx=1.0, sy=1.0):
        g = ("group", (rotate, px, py, tx, ty, sx, sy), [])
        self._stack[-1].append(g)
        self._stack.append(g[2])
        return self

    def end(self):
        self._stack.pop()
        return self

    # VectorDrawable -----------------------------------------------------------
    def to_xml(self, compact=False):
        """VectorDrawable の XML。compact=True は字下げなし・グラデーションを属性で書く小さい出力（ポートレート用）。"""
        if compact:
            return self._to_xml_compact()
        out = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tools/artgen. Do not edit by hand. -->",
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    xmlns:aapt="http://schemas.android.com/aapt"',
            '    android:width="%sdp"' % _f(self.dp_w),
            '    android:height="%sdp"' % _f(self.dp_h),
            '    android:viewportWidth="%s"' % _f(self.w),
            '    android:viewportHeight="%s">' % _f(self.h),
        ]
        self._xml_items(self.items, out, 1)
        out.append("</vector>")
        return "\n".join(out) + "\n"

    def _xml_items(self, items, out, depth):
        ind = "  " * depth
        for it in items:
            if it[0] == "group":
                rotate, px, py, tx, ty, sx, sy = it[1]
                attrs = []
                if rotate:
                    attrs += ['android:rotation="%s"' % _f(rotate)]
                if px or py:
                    attrs += ['android:pivotX="%s"' % _f(px), 'android:pivotY="%s"' % _f(py)]
                if tx or ty:
                    attrs += ['android:translateX="%s"' % _f(tx), 'android:translateY="%s"' % _f(ty)]
                if sx != 1.0 or sy != 1.0:
                    attrs += ['android:scaleX="%s"' % _f(sx), 'android:scaleY="%s"' % _f(sy)]
                out.append("%s<group %s>" % (ind, " ".join(attrs)) if attrs else "%s<group>" % ind)
                self._xml_items(it[2], out, depth + 1)
                out.append("%s</group>" % ind)
                continue
            _, d, fill, stroke, sw, alpha, salpha, cap, join, evenodd = it
            attrs = ['android:pathData="%s"' % d]
            grads = []
            if isinstance(fill, str):
                attrs.append('android:fillColor="%s"' % _argb(fill, alpha))
            elif fill is not None:
                grads.append(("android:fillColor", fill, alpha))
            if evenodd:
                attrs.append('android:fillType="evenOdd"')
            if stroke is not None and sw > 0:
                if isinstance(stroke, str):
                    attrs.append('android:strokeColor="%s"' % _argb(stroke, salpha))
                else:
                    grads.append(("android:strokeColor", stroke, salpha))
                attrs.append('android:strokeWidth="%s"' % _f(sw))
                attrs.append('android:strokeLineCap="%s"' % cap)
                attrs.append('android:strokeLineJoin="%s"' % join)
            if not grads:
                out.append("%s<path %s />" % (ind, " ".join(attrs)))
                continue
            out.append("%s<path %s>" % (ind, " ".join(attrs)))
            for name, g, a in grads:
                out.append('%s  <aapt:attr name="%s">' % (ind, name))
                if isinstance(g, Linear):
                    out.append(
                        '%s    <gradient android:type="linear" android:startX="%s" android:startY="%s" '
                        'android:endX="%s" android:endY="%s">' % (ind, _f(g.x0), _f(g.y0), _f(g.x1), _f(g.y1))
                    )
                else:
                    out.append(
                        '%s    <gradient android:type="radial" android:centerX="%s" android:centerY="%s" '
                        'android:gradientRadius="%s">' % (ind, _f(g.cx), _f(g.cy), _f(g.r))
                    )
                for off, c in g.stops:
                    out.append('%s      <item android:offset="%s" android:color="%s" />' % (ind, _f(off), _argb(c, a)))
                out.append("%s    </gradient>" % ind)
                out.append("%s  </aapt:attr>" % ind)
            out.append("%s</path>" % ind)

    def _to_xml_compact(self):
        out = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tools/artgen. Do not edit by hand. -->",
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" '
            'android:width="%sdp" android:height="%sdp" android:viewportWidth="%s" android:viewportHeight="%s">'
            % (_f(self.dp_w), _f(self.dp_h), _f(self.w), _f(self.h)),
        ]

        def col(c, a):
            s = _argb(c, a)
            return "#" + s[3:] if s.startswith("#FF") else s

        def grad(name, g, a):
            if isinstance(g, Linear):
                head = 'android:type="linear" android:startX="%s" android:startY="%s" android:endX="%s" android:endY="%s"' % (
                    _f1(g.x0), _f1(g.y0), _f1(g.x1), _f1(g.y1))
            else:
                head = 'android:type="radial" android:centerX="%s" android:centerY="%s" android:gradientRadius="%s"' % (_f1(g.cx), _f1(g.cy), _f1(g.r))
            offs = [round(o, 3) for o, _ in g.stops]
            cols = [col(c, a) for _, c in g.stops]
            if offs == [0, 1]:
                body = '<gradient %s android:startColor="%s" android:endColor="%s"/>' % (head, cols[0], cols[1])
            elif offs == [0, 0.5, 1]:
                body = '<gradient %s android:startColor="%s" android:centerColor="%s" android:endColor="%s"/>' % (head, cols[0], cols[1], cols[2])
            else:
                items = "".join('<item android:offset="%s" android:color="%s"/>' % (_f(o), c) for o, c in zip(offs, cols))
                body = "<gradient %s>%s</gradient>" % (head, items)
            return '<aapt:attr name="%s">%s</aapt:attr>' % (name, body)

        def walk(items):
            for it in items:
                if it[0] == "group":
                    rotate, px, py, tx, ty, sx, sy = it[1]
                    attrs = []
                    if rotate:
                        attrs += ['android:rotation="%s"' % _f(rotate)]
                    if px or py:
                        attrs += ['android:pivotX="%s"' % _f(px), 'android:pivotY="%s"' % _f(py)]
                    if tx or ty:
                        attrs += ['android:translateX="%s"' % _f(tx), 'android:translateY="%s"' % _f(ty)]
                    if sx != 1.0 or sy != 1.0:
                        attrs += ['android:scaleX="%s"' % _f(sx), 'android:scaleY="%s"' % _f(sy)]
                    out.append("<group %s>" % " ".join(attrs) if attrs else "<group>")
                    walk(it[2])
                    out.append("</group>")
                    continue
                _, d, fill, stroke, sw, alpha, salpha, cap, join, evenodd = it
                attrs = ['android:pathData="%s"' % d]
                inner = ""
                if isinstance(fill, str):
                    attrs.append('android:fillColor="%s"' % col(fill, alpha))
                elif fill is not None:
                    inner += grad("android:fillColor", fill, alpha)
                if evenodd:
                    attrs.append('android:fillType="evenOdd"')
                if stroke is not None and sw > 0:
                    if isinstance(stroke, str):
                        attrs.append('android:strokeColor="%s"' % col(stroke, salpha))
                    else:
                        inner += grad("android:strokeColor", stroke, salpha)
                    attrs.append('android:strokeWidth="%s"' % _f(sw))
                    if d.count("M") != d.count("Z"):   # 閉じた形だけなら端の形は関係ない
                        attrs.append('android:strokeLineCap="%s"' % cap)
                    attrs.append('android:strokeLineJoin="%s"' % join)
                out.append("<path %s>%s</path>" % (" ".join(attrs), inner) if inner else "<path %s/>" % " ".join(attrs))

        walk(self.items)
        out.append("</vector>")
        return "\n".join(out) + "\n"

    # SVG（確認用） --------------------------------------------------------------
    def to_svg(self, size=None, uid="g"):
        defs, body = [], []
        counter = [0]

        def paint(p, a):
            if p is None:
                return "none", 1.0
            if isinstance(p, str):
                c = p.lstrip("#")
                if len(c) == 8:
                    return "#" + c[2:], int(c[0:2], 16) / 255.0
                return p, a
            counter[0] += 1
            gid = "%s%d" % (uid, counter[0])
            stops = ""
            for off, c in p.stops:
                cc = c.lstrip("#")
                op = 1.0
                if len(cc) == 8:
                    op = int(cc[0:2], 16) / 255.0
                    cc = cc[2:]
                stops += '<stop offset="%s" stop-color="#%s" stop-opacity="%s"/>' % (_f(off), cc, _f(op * a))
            if isinstance(p, Linear):
                defs.append(
                    '<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%s" y1="%s" x2="%s" y2="%s">%s'
                    "</linearGradient>" % (gid, _f(p.x0), _f(p.y0), _f(p.x1), _f(p.y1), stops)
                )
            else:
                defs.append(
                    '<radialGradient id="%s" gradientUnits="userSpaceOnUse" cx="%s" cy="%s" r="%s">%s'
                    "</radialGradient>" % (gid, _f(p.cx), _f(p.cy), _f(p.r), stops)
                )
            return "url(#%s)" % gid, 1.0

        def walk(items):
            for it in items:
                if it[0] == "group":
                    rotate, px, py, tx, ty, sx, sy = it[1]
                    tr = "translate(%s %s) translate(%s %s) rotate(%s) scale(%s %s) translate(%s %s)" % (
                        _f(tx), _f(ty), _f(px), _f(py), _f(rotate), _f(sx), _f(sy), _f(-px), _f(-py),
                    )
                    body.append('<g transform="%s">' % tr)
                    walk(it[2])
                    body.append("</g>")
                    continue
                _, d, fill, stroke, sw, alpha, salpha, cap, join, evenodd = it
                f, fo = paint(fill, alpha)
                s, so = paint(stroke if sw > 0 else None, salpha)
                body.append(
                    '<path d="%s" fill="%s" fill-opacity="%s" stroke="%s" stroke-opacity="%s" stroke-width="%s" '
                    'stroke-linecap="%s" stroke-linejoin="%s" fill-rule="%s"/>'
                    % (d, f, _f(fo), s, _f(so), _f(sw), cap, join, "evenodd" if evenodd else "nonzero")
                )

        walk(self.items)
        w = size or self.dp_w
        h = (size * self.h / self.w) if size else self.dp_h
        return '<svg xmlns="http://www.w3.org/2000/svg" width="%s" height="%s" viewBox="0 0 %s %s"><defs>%s</defs>%s</svg>' % (
            _f(w), _f(h), _f(self.w), _f(self.h), "".join(defs), "".join(body),
        )


# ---- 曲線・帯・切り抜き・色の部品（ポートレート gen_portraits.py 用。既存の API はそのまま） --------
def _f1(v):
    s = "%.1f" % v
    if s.endswith(".0"):
        s = s[:-2]
    return "0" if s in ("-0", "") else s


def _pt(p):
    return "%s,%s" % (_f1(p[0]), _f1(p[1]))


def _tangent(pts, i, closed):
    n = len(pts)
    p = pts[i]
    s = p[2] if len(p) > 2 else 1.0
    if s == 0:
        return (0.0, 0.0)
    if closed:
        a, b = pts[(i - 1) % n], pts[(i + 1) % n]
    else:
        a, b = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
    return ((b[0] - a[0]) / 6.0 * s, (b[1] - a[1]) / 6.0 * s)


def _segments(pts, closed):
    """Catmull-Rom の各区間を 3 次ベジェ (p0, c1, c2, p1) にして返す。"""
    n = len(pts)
    out = []
    for i in range(n if closed else n - 1):
        j = (i + 1) % n
        t0, t1 = _tangent(pts, i, closed), _tangent(pts, j, closed)
        p0, p1 = pts[i], pts[j]
        out.append(((p0[0], p0[1]), (p0[0] + t0[0], p0[1] + t0[1]), (p1[0] - t1[0], p1[1] - t1[1]), (p1[0], p1[1])))
    return out


def spline(pts, closed=True):
    """点列を通るなめらかな曲線（Catmull-Rom → 3 次ベジェ）のパス文字列。座標は小数 1 桁。

    点は (x, y) か (x, y, s)。s は接線の強さ（0 = 角、1 = 標準、その間 = きつめの曲がり）。
    """
    segs = _segments(pts, closed)
    d = ["M" + _pt(pts[0])]
    first = True
    for p0, c1, c2, p1 in segs:
        if c1 == p0 and c2 == p1:
            d.append("L" + _pt(p1))
        elif first:
            d.append("C%s %s %s" % (_pt(c1), _pt(c2), _pt(p1)))
        else:
            # 接線が連続（角では制御点 = 端点）なので、最初の制御点は S で省ける
            d.append("S%s %s" % (_pt(c2), _pt(p1)))
        first = False
    return " ".join(d) + (" Z" if closed else "")


def spline_pts(pts, closed=True, n=6):
    """spline() と同じ曲線を折れ線にした点列（計算用）。"""
    out = []
    for p0, c1, c2, p1 in _segments(pts, closed):
        for k in range(n):
            t = k / n
            u = 1 - t
            out.append((
                u * u * u * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * p1[0],
                u * u * u * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * p1[1],
            ))
    if not closed:
        out.append((pts[-1][0], pts[-1][1]))
    return out


def quad_pts(p0, c, p1, n=8):
    """2 次ベジェを折れ線にした点列（両端を含む）。"""
    out = []
    for k in range(n + 1):
        t = k / n
        u = 1 - t
        out.append((u * u * p0[0] + 2 * u * t * c[0] + t * t * p1[0], u * u * p0[1] + 2 * u * t * c[1] + t * t * p1[1]))
    return out


def poly1(pts, closed=True):
    """poly() の小数 1 桁版。"""
    d = "M" + " L".join(_pt(p) for p in pts)
    return d + (" Z" if closed else "")


def ribbon(pts, widths):
    """中心線 pts（なめらかにつなぐ）に沿った、太さの変わる帯の閉じたパス。widths は各点での太さ（0 で尖る）。

    髪の束・まゆ・ハイライトなど、入り抜きのある線に使う。
    """
    n = len(pts)
    if not isinstance(widths, (list, tuple)):
        widths = [widths] * n
    if len(widths) != n:  # (始点, 中央, 終点) の 3 値を線形に補間
        ws = []
        for i in range(n):
            t = i / (n - 1) * (len(widths) - 1)
            k = min(int(t), len(widths) - 2)
            ws.append(widths[k] + (widths[k + 1] - widths[k]) * (t - k))
        widths = ws
    left, right = [], []
    for i in range(n):
        a, b = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        ln = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / ln, dx / ln
        h = widths[i] / 2.0
        if h <= 0.16 and i in (0, n - 1):   # 細い端は 1 点に尖らせる（点が減ってパスが短くなる）
            left.append((pts[i][0], pts[i][1], 0))
            right.append(None)
        else:
            left.append((pts[i][0] + nx * h, pts[i][1] + ny * h))
            right.append((pts[i][0] - nx * h, pts[i][1] - ny * h))
    loop = left + [p for p in reversed(right) if p is not None]
    return spline(loop, closed=True)


def clip_convex(subject, clip):
    """多角形 subject を凸多角形 clip で切り抜く（Sutherland–Hodgman）。clipPath を使わずに目の虹彩などを収める。"""
    area = 0.0
    for i in range(len(clip)):
        x0, y0 = clip[i]
        x1, y1 = clip[(i + 1) % len(clip)]
        area += x0 * y1 - x1 * y0
    sign = 1.0 if area > 0 else -1.0
    out = [(p[0], p[1]) for p in subject]
    for i in range(len(clip)):
        ax, ay = clip[i]
        bx, by = clip[(i + 1) % len(clip)]
        src, out = out, []
        if not src:
            break

        def inside(p):
            return sign * ((bx - ax) * (p[1] - ay) - (by - ay) * (p[0] - ax)) >= 0

        def cross(p, q):
            x1, y1, x2, y2 = p[0], p[1], q[0], q[1]
            den = (x1 - x2) * (ay - by) - (y1 - y2) * (ax - bx)
            if abs(den) < 1e-9:
                return q
            t = ((x1 - ax) * (ay - by) - (y1 - ay) * (ax - bx)) / den
            return (x1 + t * (x2 - x1), y1 + t * (y2 - y1))

        prev = src[-1]
        for cur in src:
            if inside(cur):
                if not inside(prev):
                    out.append(cross(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cross(prev, cur))
            prev = cur
    return out


def ellipse_pts(cx, cy, rx, ry, n=20, a0=0.0):
    return [(cx + rx * math.cos(a0 + 2 * math.pi * i / n), cy + ry * math.sin(a0 + 2 * math.pi * i / n)) for i in range(n)]


def mirror_pts(pts, cx):
    """x = cx で左右を反転した点列（向きが変わらないよう順序も逆にする）。"""
    return [((2 * cx - p[0],) + tuple(p[1:])) for p in reversed(pts)]


def _rgb(c):
    c = c.lstrip("#")
    if len(c) == 8:
        c = c[2:]
    return int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)


def mix(c1, c2, t):
    """2 色を混ぜる（t = 0 で c1、1 で c2）。"""
    a, b = _rgb(c1), _rgb(c2)
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(a[i] + (b[i] - a[i]) * t))) for i in range(3))


def lighten(c, t):
    return mix(c, "#FFFFFF", t)


def darken(c, t):
    return mix(c, "#000000", t)


def rgba(c, a):
    """'#RRGGBB' と不透明度から、グラデーションの stop に使う '#AARRGGBB'。"""
    return _argb(c, a)
